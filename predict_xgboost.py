"""
Batch prediction with the finalized XGBoost model.

The input must already contain the graph-enhanced features generated by the
project pipeline. The script ranks one input batch and flags its top 1,000
scores, or all rows when --all-rows is requested.
"""

from pathlib import Path
import argparse
import json

import numpy as np
import polars as pl
import xgboost as xgb


BASE_DIR = Path(__file__).resolve().parent
CONFIG_PATH = BASE_DIR / "processed" / "final_xgboost_config.json"
DEFAULT_INPUT = (
    BASE_DIR / "processed" / "transactions_with_graph_features.parquet"
)
DEFAULT_OUTPUT = BASE_DIR / "processed" / "predictions.csv"

parser = argparse.ArgumentParser(
    description="Score graph-enhanced transaction features with XGBoost."
)
parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
parser.add_argument(
    "--all-rows",
    action="store_true",
    help="Score all input rows instead of only rows after validation_end.",
)
args = parser.parse_args()

if not CONFIG_PATH.exists():
    raise FileNotFoundError(f"Configuration not found: {CONFIG_PATH}")
if not args.input.exists():
    raise FileNotFoundError(f"Input file not found: {args.input}")

config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
model_path = BASE_DIR / config["model_path"]
if not model_path.exists():
    raise FileNotFoundError(f"Model not found: {model_path}")

features = config["features"]
categorical_features = config["categorical_features"]
alert_budget = int(config["alert_budget"])
validation_end = config["validation_end"]
validation_end_datetime = (
    pl.Series([validation_end])
    .str.strptime(pl.Datetime, strict=False)
    .item()
)
train_end_datetime = (
    pl.Series([config["train_end"]])
    .str.strptime(pl.Datetime, strict=False)
    .item()
)

frame = (
    pl.scan_parquet(args.input)
    .with_row_index("transaction_id")
    .select([
        "transaction_id",
        "timestamp",
        "from_account",
        "to_account",
        *features,
        "is_laundering",
    ])
    .collect(engine="streaming")
)

if not args.all_rows:
    frame = frame.filter(
        pl.col("timestamp") >= validation_end_datetime
    )

if frame.is_empty():
    raise RuntimeError("No rows remain after input filtering.")

training_rows = (
    pl.scan_parquet(args.input)
    .filter(pl.col("timestamp") < train_end_datetime)
    .select(categorical_features)
    .collect(engine="streaming")
)

mappings = {}
for column in categorical_features:
    values = (
        training_rows.select(
            pl.col(column).cast(pl.String).fill_null("__MISSING__")
        )
        .unique()
        .sort(column)
        .get_column(column)
        .to_list()
    )
    mappings[column] = {value: index for index, value in enumerate(values)}

frame = frame.with_columns([
    pl.col(column)
    .cast(pl.String)
    .replace_strict(mappings[column], default=-1)
    .cast(pl.Int32)
    .alias(column)
    for column in categorical_features
])

model = xgb.XGBClassifier()
model.load_model(model_path)
matrix = frame.select(features).to_numpy()
probabilities = model.predict_proba(matrix)[:, 1]

budget = min(alert_budget, len(probabilities))
order = np.argsort(-probabilities, kind="stable")
alert_ids = set(order[:budget].tolist())
ranking = np.empty(len(probabilities), dtype=np.int64)
ranking[order] = np.arange(1, len(probabilities) + 1)

output = frame.select([
    "transaction_id",
    "timestamp",
    "from_account",
    "to_account",
    "is_laundering",
]).with_columns([
    pl.Series("laundering_probability", probabilities),
    pl.Series(
        "alert_rank",
        [
            int(ranking[index]) if index in alert_ids else None
            for index in range(len(probabilities))
        ],
        dtype=pl.Int64,
    ),
    pl.Series(
        "is_alert",
        [index in alert_ids for index in range(len(probabilities))],
        dtype=pl.Boolean,
    ),
])

output_path = args.output.resolve()
output_path.parent.mkdir(parents=True, exist_ok=True)
output.write_csv(output_path)

print(f"Rows scored: {len(output):,}")
print(f"Alerts selected: {len(alert_ids):,}")
print(f"Saved predictions: {output_path}")
