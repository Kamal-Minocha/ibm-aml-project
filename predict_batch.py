"""
Score a prepared transaction batch with the finalized XGBoost model.

The input must already contain the graph-enhanced feature columns generated by
the project pipeline. Raw transactions alone are not sufficient because the
model requires historical and network features.
"""

from pathlib import Path
import argparse
import json

import numpy as np
import polars as pl
import xgboost as xgb


BASE_DIR = Path(__file__).resolve().parent
CONFIG_PATH = BASE_DIR / "processed" / "final_xgboost_config.json"
TRAINING_FEATURE_PATH = (
    BASE_DIR / "processed" / "transactions_with_graph_features.parquet"
)

parser = argparse.ArgumentParser()
parser.add_argument("--input", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
parser.add_argument(
    "--alerts",
    type=int,
    default=1000,
    help="Maximum number of top-ranked alerts to select.",
)
args = parser.parse_args()

if args.alerts <= 0:
    raise ValueError("--alerts must be greater than zero.")

config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
model_path = BASE_DIR / config["model_path"]
features = config["features"]
categorical_features = config["categorical_features"]

if not args.input.exists():
    raise FileNotFoundError(f"Input batch not found: {args.input}")
if not model_path.exists():
    raise FileNotFoundError(f"Model not found: {model_path}")

if args.input.suffix.lower() == ".csv":
    source = pl.scan_csv(args.input, infer_schema_length=10000)
elif args.input.suffix.lower() == ".parquet":
    source = pl.scan_parquet(args.input)
else:
    raise ValueError("Input must be a .csv or .parquet file.")

available = source.collect_schema().names()
missing = [column for column in features if column not in available]
if missing:
    raise ValueError(
        "The batch is not model-ready. Missing engineered columns:\n"
        + "\n".join(missing)
        + "\nRun the preprocessing, account-join, behavior, and graph "
        "feature stages first."
    )

optional_columns = [
    column
    for column in [
        "transaction_id",
        "timestamp",
        "from_account",
        "to_account",
        "is_laundering",
    ]
    if column in available
]
frame = source.select([*optional_columns, *features]).collect(
    engine="streaming"
)

training = (
    pl.scan_parquet(TRAINING_FEATURE_PATH)
    .filter(
        pl.col("timestamp")
        < pl.datetime(2022, 9, 7, 14, 55)
    )
    .select(categorical_features)
    .collect(engine="streaming")
)

for column in categorical_features:
    values = (
        training.select(
            pl.col(column).cast(pl.String).fill_null("__MISSING__")
        )
        .unique()
        .sort(column)
        .get_column(column)
        .to_list()
    )
    mapping = {value: index for index, value in enumerate(values)}
    frame = frame.with_columns(
        pl.col(column)
        .cast(pl.String)
        .replace_strict(mapping, default=-1)
        .cast(pl.Int32)
        .alias(column)
    )

model = xgb.XGBClassifier()
model.load_model(model_path)
probabilities = model.predict_proba(frame.select(features).to_numpy())[:, 1]

budget = min(args.alerts, frame.height)
order = np.argsort(-probabilities, kind="stable")
selected = np.zeros(frame.height, dtype=bool)
selected[order[:budget]] = True
ranking = np.empty(frame.height, dtype=np.int64)
ranking[order] = np.arange(1, frame.height + 1)

output = frame.select(optional_columns).with_columns([
    pl.Series("laundering_probability", probabilities),
    pl.Series("alert_rank", [
        int(rank) if selected[index] else None
        for index, rank in enumerate(ranking)
    ], dtype=pl.Int64),
    pl.Series("is_alert", selected),
]).sort("laundering_probability", descending=True)

args.output.parent.mkdir(parents=True, exist_ok=True)
output.write_csv(args.output)

print(f"Rows scored: {frame.height:,}")
print(f"Alerts selected: {budget:,}")
print(f"Saved: {args.output.resolve()}")
